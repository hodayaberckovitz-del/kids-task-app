export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
};

// Detect system language
const detectSystemLanguage = () => {
  try {
    // Get browser/system language
    const browserLang = navigator.language || navigator.userLanguage;
    // Extract language code (e.g., 'he-IL' -> 'he', 'en-US' -> 'en')
    const langCode = browserLang.split('-')[0].toLowerCase();
    
    // Check if detected language is supported
    if (translations[langCode]) {
      console.log('Detected system language:', langCode);
      return langCode;
    }
    
    // Default to Hebrew if not supported
    console.log('System language not supported, defaulting to Hebrew');
    return 'he';
  } catch (error) {
    console.error('Error detecting system language:', error);
    return 'he';
  }
};

